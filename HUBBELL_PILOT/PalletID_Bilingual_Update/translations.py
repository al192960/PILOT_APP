def tr(language, key, **kwargs):
    """
    Return translated text for the selected language.
    Falls back to English, then to the key itself.
    """
    language = language if language in TEXTS else "en"

    text = (
        TEXTS.get(language, {}).get(key)
        or TEXTS["en"].get(key)
        or key
    )

    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text

    return text
